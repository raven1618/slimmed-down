class Globe:
    def __init__(self, cx, cy, r, lon0=-25.0, tilt=22.0):
        self.cx, self.cy, self.r = cx, cy, r
        self.lon0, self.tilt = math.radians(lon0), math.radians(tilt)

    def vec(self, lat, lon):
        la, lo = math.radians(lat), math.radians(lon)
        return (math.cos(la) * math.cos(lo), math.cos(la) * math.sin(lo), math.sin(la))

    def project(self, v, lift=1.0):
        x, y, z = v
        # rotate around z by -lon0
        c, s = math.cos(-self.lon0), math.sin(-self.lon0)
        x, y = x * c - y * s, x * s + y * c
        # tilt around y axis
        ct, st = math.cos(self.tilt), math.sin(self.tilt)
        x, z = x * ct + z * st, -x * st + z * ct
        # x now points toward viewer
        return (self.cx + y * self.r * lift, self.cy - z * self.r * lift, x)

    def dots(self, step=3.2, dot=1.6, colour="#FFFFFF", base_op=0.7):
        out = []
        lat = -84.0
        while lat <= 84:
            ring = max(1, int(360 * math.cos(math.radians(lat)) / step))
            for i in range(ring):
                lon = -180 + 360 * i / ring + (lat * 7 % step)
                px, py, depth = self.project(self.vec(lat, lon))
                if depth > 0.02:
                    op = base_op * (0.25 + 0.75 * depth)
                    out.append(f'<circle cx="{n(px)}" cy="{n(py)}" r="{n(dot * (0.55 + 0.45 * depth))}" fill="{colour}" fill-opacity="{n(op)}"/>')
            lat += step
        return "".join(out)

    def arc(self, a, b_, height=0.10, steps=64):
        va, vb = self.vec(*a), self.vec(*b_)
        dot = max(-1, min(1, sum(p * q for p, q in zip(va, vb))))
        om = math.acos(dot)
        pts = []
        for i in range(steps + 1):
            t = i / steps
            if om < 1e-6:
                v = va
            else:
                s1 = math.sin((1 - t) * om) / math.sin(om)
                s2 = math.sin(t * om) / math.sin(om)
                v = tuple(s1 * p + s2 * q for p, q in zip(va, vb))
            lift = 1 + height * math.sin(math.pi * t) * (om / math.pi * 1.6 + 0.3)
            px, py, depth = self.project(v, lift)
            pts.append((px, py, depth))
        return pts


HUB_ES = {"New York": "Nueva York", "Rotterdam": "Róterdam", "Dubai": "Dubái"}


def globe_layer(g: Globe, dot_colour="#FFFFFF", route_op=0.9, labels=False, step=3.2, dot=1.9, lang="en"):
    parts = [g.dots(step=step, dot=dot, colour=dot_colour)]
    for a, c, main in ROUTES:
        pts = g.arc(HUBS[a], HUBS[c])
        d = "M" + " L".join(f"{n(x)} {n(y)}" for x, y, z in pts if z > -0.15)
        col = b.ORANGE if main else "#FFFFFF"
        op = route_op if main else route_op * 0.45
        w = 2.4 if main else 1.2
        parts.append(f'<path d="{d}" fill="none" stroke="{col}" stroke-opacity="{n(op)}" stroke-width="{w}" stroke-linecap="round"/>')
    for name, (lat, lon) in HUBS.items():
        x, y, z = g.project(g.vec(lat, lon))
        if z > 0.05:
            parts.append(f'<circle cx="{n(x)}" cy="{n(y)}" r="9" fill="{b.ORANGE}" fill-opacity=".18"/>'
                         f'<circle cx="{n(x)}" cy="{n(y)}" r="3.6" fill="{b.ORANGE}"/>')
            if labels and name not in ("Felixstowe", "Hamburg", "Algeciras"):
                parts.append(f'<text x="{n(x + 12)}" y="{n(y + 4)}" fill="#FFFFFF" fill-opacity=".75" font-family="{FONT}" font-size="12" letter-spacing="1.5">{(HUB_ES.get(name, name) if lang == "es" else name).upper()}</text>')
    return "".join(parts)


