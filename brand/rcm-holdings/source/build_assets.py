def tint_scale():
    scales = {
        "navy": [100, 80, 60, 40, 20, 10],
        "graphite": [100, 75, 50, 25, 10],
        "stone": [100, 50],
        "orange": [100, 80, 60, 40, 20],
    }
    base = {"navy": b.NAVY, "graphite": b.GRAPHITE, "stone": b.STONE, "orange": b.ORANGE}
    return {k: {str(s): b.mix(base[k], b.WHITE, s / 100) for s in v} for k, v in scales.items()}


COLOUR_NAMES_ES = {"navy": "Azul Marino", "graphite": "Grafito", "stone": "Piedra",
                   "orange": "Rojo Anaranjado", "white": "Blanco"}


def palette_sheet(lang="en"):
    W, H = 1500, 560
    body = [f'<rect width="{W}" height="{H}" fill="#FFFFFF"/>']
    sw = (W - 120) / 5
    for i, s in enumerate(b.PALETTE):
        x = 60 + i * sw
        txt = b.WHITE if s.key in ("navy", "graphite", "orange") else b.NAVY
        stroke = ' stroke="#E6E7E9"' if s.key == "white" else ""
        r, g, bl = b.hex_to_rgb(s.hex)
        c, m, y, k = s.cmyk
        name = COLOUR_NAMES_ES[s.key] if lang == "es" else s.name
        body.append(f'<rect x="{n(x)}" y="60" width="{n(sw)}" height="300" fill="{s.hex}"{stroke}/>')
        body.append(f'<text x="{n(x + 24)}" y="300" fill="{txt}" font-family="{FONT}" font-size="15" font-weight="600" letter-spacing="2.4">{name.upper()}</text>')
        body.append(f'<text x="{n(x + 24)}" y="326" fill="{txt}" font-family="{FONT}" font-size="15" letter-spacing="2.4" opacity=".85">{s.hex}</text>')
        lines = [f"RGB {r} {g} {bl}", f"CMYK {c} {m} {y} {k}", s.pantone, f"{s.ral}"]
        for j, line in enumerate(lines):
            body.append(f'<text x="{n(x + 2)}" y="{400 + j * 26}" fill="{b.GRAPHITE}" font-family="{FONT}" font-size="15">{line}</text>')
    title = "RCM Holdings — Paleta de color" if lang == "es" else "RCM Holdings colour palette"
    return svg_doc(W, H, "".join(body), title)


def build_colour():
    tints = tint_scale()
    core = {s.key: s for s in b.PALETTE}

    # CSS
    css = ["/* RCM Holdings — colour & type tokens. Generated by source/build_assets.py */", ":root {"]
    for s in b.PALETTE:
        css.append(f"  --rcm-{s.key}: {s.hex};")
    css.append("")
    for k, scale in tints.items():
        for step, hx in scale.items():
            if step != "100":
                css.append(f"  --rcm-{k}-{step}: {hx};")
    css += [
        "",
        "  /* Semantic roles */",
        "  --rcm-text: var(--rcm-graphite);",
        "  --rcm-text-strong: var(--rcm-navy);",
        "  --rcm-text-muted: var(--rcm-graphite-75);",
        "  --rcm-surface: var(--rcm-white);",
        "  --rcm-surface-alt: #F7F7F8;",
        "  --rcm-surface-inverse: var(--rcm-navy);",
        "  --rcm-border: var(--rcm-stone);",
        "  --rcm-accent: var(--rcm-orange);",
        "",
        "  /* Typography */",
        "  --rcm-font-primary: 'Aktiv Grotesk', 'Inter', 'Helvetica Neue', Arial, sans-serif;",
        "  --rcm-font-secondary: 'Inter', 'Helvetica Neue', Arial, sans-serif;",
        "  --rcm-tracking-eyebrow: 0.18em;",
        "}",
        "",
    ]
    b.write("color/rcm-colors.css", "\n".join(css))

    # SCSS
    scss = ["// RCM Holdings — colour tokens. Generated by source/build_assets.py"]
    for s in b.PALETTE:
        scss.append(f"$rcm-{s.key}: {s.hex};")
    for k, scale in tints.items():
        for step, hx in scale.items():
            if step != "100":
                scss.append(f"$rcm-{k}-{step}: {hx};")
    scss += ["", "$rcm-palette: ("] + [f"  '{s.key}': {s.hex}," for s in b.PALETTE] + [");",
             "", "$rcm-font-primary: 'Aktiv Grotesk', 'Inter', 'Helvetica Neue', Arial, sans-serif;",
             "$rcm-font-secondary: 'Inter', 'Helvetica Neue', Arial, sans-serif;", ""]
    b.write("color/rcm-colors.scss", "\n".join(scss))

    # Design tokens (W3C DTCG format)
    tokens = {"rcm": {"color": {}, "font": {}}}
    for s in b.PALETTE:
        tokens["rcm"]["color"][s.key] = {
            "$type": "color", "$value": s.hex,
            "$description": f"{s.name}. {s.role}",
            "$extensions": {"rcm": {
                "rgb": list(b.hex_to_rgb(s.hex)), "cmyk": list(s.cmyk),
                "pantone": s.pantone, "ral": s.ral, "usage_share_percent": s.share}},
        }
    for k, scale in tints.items():
        for step, hx in scale.items():
            if step != "100":
                tokens["rcm"]["color"][f"{k}-{step}"] = {"$type": "color", "$value": hx,
                                                         "$description": f"{core[k].name} {step}% tint"}
    tokens["rcm"]["font"] = {
        "primary": {"$type": "fontFamily", "$value": ["Aktiv Grotesk", "Inter", "Helvetica Neue", "Arial", "sans-serif"]},
        "secondary": {"$type": "fontFamily", "$value": ["Inter", "Helvetica Neue", "Arial", "sans-serif"]},
    }
    b.write("color/rcm-tokens.json", json.dumps(tokens, indent=2) + "\n")

    # Tailwind preset
    tw_colors = {s.key: s.hex for s in b.PALETTE}
    for k, scale in tints.items():
        for step, hx in scale.items():
            if step != "100":
                tw_colors[f"{k}-{step}"] = hx
    tw = (
        "// RCM Holdings Tailwind preset — add to tailwind.config: presets: [require('./tailwind.rcm.cjs')]\n"
        "module.exports = {\n  theme: {\n    extend: {\n      colors: {\n        rcm: "
        + json.dumps(tw_colors, indent=10).replace("\n}", "\n        }")
        + ",\n      },\n      fontFamily: {\n"
        "        'rcm-primary': ['Aktiv Grotesk', 'Inter', 'Helvetica Neue', 'Arial', 'sans-serif'],\n"
        "        'rcm-secondary': ['Inter', 'Helvetica Neue', 'Arial', 'sans-serif'],\n"
        "      },\n      letterSpacing: { eyebrow: '0.18em' },\n    },\n  },\n};\n"
    )
    b.write("color/tailwind.rcm.cjs", tw)

    # GIMP / Inkscape / Affinity palette
    gpl = ["GIMP Palette", "Name: RCM Holdings", "Columns: 5", "#"]
    for s in b.PALETTE:
        r, g, bl = b.hex_to_rgb(s.hex)
        gpl.append(f"{r:3d} {g:3d} {bl:3d}\t{s.name} {s.hex}")
    for k, scale in tints.items():
        for step, hx in scale.items():
            if step != "100":
                r, g, bl = b.hex_to_rgb(hx)
                gpl.append(f"{r:3d} {g:3d} {bl:3d}\t{core[k].name} {step}% {hx}")
    b.write("color/RCM-Holdings.gpl", "\n".join(gpl) + "\n")

    # Adobe Swatch Exchange (.ase)
    def ase_name(s):
        enc = (s + "\0").encode("utf-16-be")
        return struct.pack(">H", len(enc) // 2) + enc

    def ase_colour(name, hx, ctype=0):
        r, g, bl = (c / 255 for c in b.hex_to_rgb(hx))
        body = ase_name(name) + b"RGB " + struct.pack(">fff", r, g, bl) + struct.pack(">H", ctype)
        return struct.pack(">HI", 0x0001, len(body)) + body

    blocks = []
    gname = ase_name("RCM Holdings")
    blocks.append(struct.pack(">HI", 0xC001, len(gname)) + gname)
    for s in b.PALETTE:
        blocks.append(ase_colour(f"RCM {s.name}", s.hex))
    blocks.append(struct.pack(">HI", 0xC002, 0))
    gname = ase_name("RCM Holdings — Tints")
    blocks.append(struct.pack(">HI", 0xC001, len(gname)) + gname)
    for k, scale in tints.items():
        for step, hx in scale.items():
            if step != "100":
                blocks.append(ase_colour(f"RCM {core[k].name} {step}%", hx))
    blocks.append(struct.pack(">HI", 0xC002, 0))
    ase = b"ASEF" + struct.pack(">HHI", 1, 0, len(blocks)) + b"".join(blocks)
    full = os.path.join(b.ROOT, "color", "RCM-Holdings.ase")
    with open(full, "wb") as fh:
        fh.write(ase)

    # Small swatches (README / docs)
    for s_ in b.PALETTE:
        stroke = ' stroke="#C9CCD1"' if s_.key == "white" else ""
        b.write(f"color/swatches/rcm-swatch-{s_.key}.svg",
                f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 36 36" width="36" height="36"><title>{s_.name} {s_.hex}</title>'
                f'<rect x=".5" y=".5" width="35" height="35" fill="{s_.hex}"{stroke}/></svg>\n')

    # Visual swatch sheets
    for lang, rel in (("en", "color/rcm-palette.svg"), ("es", "color/rcm-palette-es.svg")):
        b.write(rel, palette_sheet(lang))
        png_jobs.append({"svg": rel, "png": rel.replace(".svg", ".png"), "width": 1500})


