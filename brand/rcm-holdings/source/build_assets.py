def guides(cx, cy, r, extra=""):
    c = "#C9CCD1"
    return (f'<g fill="none" stroke="{c}" stroke-width="1">'
            f'<circle cx="{cx}" cy="{cy}" r="{r}"/>'
            f'<path d="M{cx - r * 1.35} {cy}H{cx + r * 1.35} M{cx} {cy - r * 1.35}V{cy + r * 1.35}"/>{extra}</g>')


def exploration(idx):
    S = 400
    c = S / 2
    if idx == 1:  # Origin — the chosen direction, with construction
        body = guides(c, c, 128, f'<path d="M{c} {c-128}L{c+128} {c}L{c} {c+128}L{c-128} {c}Z"/>')
        body += b.symbol_svg(220, c - 110, c - 110, b.NAVY, b.ORANGE, inner=0.5, gap=0.16)
        label = "Origin"
    elif idx == 2:  # Rotation — pinwheel
        R = 110
        q = b.symbol_quadrant(R, inner=0.42, gap=0.10, fillet=0.06)
        parts = []
        for k, (sx, sy, dx, dy, col) in enumerate([(1, 1, 18, -18, b.NAVY), (-1, 1, 18, 18, b.NAVY),
                                                   (-1, -1, -18, 18, b.ORANGE), (1, -1, -18, -18, b.NAVY)]):
            d = b.path_d(q, (sx, 0, 0, sy, c + dx, c + dy))
            parts.append(f'<path fill="{col}" d="{d}"/>')
        body = guides(c, c, 150, f'<path d="M{c} {c-150}L{c+150} {c}L{c} {c+150}L{c-150} {c}Z"/>') + "".join(parts)
        label = "Rotation"
    elif idx == 3:  # Compass — elongated
        p = b.symbol_paths(220, 0, 0, inner=0.5, gap=0.07)
        cols = {"tl": b.NAVY, "tr": b.ORANGE, "bl": b.NAVY, "br": b.NAVY}
        inner = "".join(f'<path fill="{cols[k]}" d="{p[k]}"/>' for k in p)
        body = guides(c, c, 150, f'<path d="M{c-75} {c-120}L{c+75} {c+120} M{c+75} {c-120}L{c-75} {c+120}"/>')
        body += f'<g transform="translate({c - 85} {c - 160}) scale({170/220} {320/220})">{inner}</g>'
        label = "Compass"
    elif idx == 4:  # Linkage — interlocking chevrons with forward arrow
        w = 30
        body = guides(c, c, 0, "")
        body = (f'<g fill="none" stroke-width="{w}" stroke-linejoin="miter">'
                f'<path stroke="{GREY}" d="M{c-70} {c-10} L{c} {c-80} L{c+40} {c-40}"/>'
                f'<path stroke="{b.NAVY}" d="M{c+5} {c-45} L{c+75} {c+25} L{c+5} {c+95}"/>'
                f'<path stroke="{b.ORANGE}" d="M{c-120} {c+5} L{c-75} {c+50} L{c-20} {c+50}"/></g>'
                f'<path fill="{b.NAVY}" d="M{c+95} {c-30}L{c+150} {c-30}L{c+150} {c-50}L{c+190} {c-20}L{c+150} {c+10}L{c+150} {c-10}L{c+95} {c-10}Z"/>'
                f'<rect x="{c-30}" y="{c-55}" width="140" height="14" fill="#FFFFFF"/>')
        label = "Linkage"
    else:  # Facet — asymmetric weights
        R = 115
        heavy = b.symbol_quadrant(R, inner=0.45, gap=0.10, fillet=0.05)
        light = b.symbol_quadrant(R, inner=0.66, gap=0.10, fillet=0.05)
        parts = [f'<path fill="{b.NAVY}" d="{b.path_d(heavy, (1, 0, 0, 1, c, c))}"/>',
                 f'<path fill="{b.NAVY}" d="{b.path_d(heavy, (1, 0, 0, -1, c, c))}"/>',
                 f'<path fill="{GREY}" d="{b.path_d(light, (-1, 0, 0, 1, c, c))}"/>',
                 f'<path fill="{b.ORANGE}" d="{b.path_d(heavy, (-1, 0, 0, -1, c, c))}"/>']
        body = guides(c, c, 0, f'<path d="M{c} {c-170}V{c+170} M{c-170} {c}H{c+170}"/>') + "".join(parts)
        label = "Facet"
    return svg_doc(S, S, f'<rect width="{S}" height="{S}" fill="#FFFFFF"/>' + body,
                   f"RCM Holdings symbol exploration {idx:02d} — {label}")


